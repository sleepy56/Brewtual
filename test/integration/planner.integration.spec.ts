import { PrismaClient } from '@prisma/client';
import { randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { PrismaService } from '../../src/server/database/prisma.service';
import { createServices } from '../../src/server/services';
import type { Services } from '../../src/server/services';

describe('personal planner with real PostgreSQL transactions', () => {
  const schema=`test_${randomUUID().replace(/-/g,'')}`;
  let db:PrismaService, admin:PrismaClient|undefined, services:Services;
  const alice={id:randomUUID(),email:`alice-${randomUUID()}@example.test`};
  const bob={id:randomUUID(),email:`bob-${randomUUID()}@example.test`};
  const carol={id:randomUUID(),email:`carol-${randomUUID()}@example.test`};
  const now=new Date('2026-10-23T10:00:00Z');
  beforeAll(async()=>{
    const connection=process.env.TEST_DATABASE_URL;
    if(!connection)throw new Error('Set TEST_DATABASE_URL to a disposable local PostgreSQL database.');
    if(!['localhost','127.0.0.1','[::1]'].includes(new URL(connection).hostname))throw new Error('Integration tests require local PostgreSQL, never a hosted database.');
    admin=new PrismaClient({datasourceUrl:connection});
    await admin.$executeRawUnsafe(`CREATE SCHEMA "${schema}"`);
    const scoped=new URL(connection);scoped.searchParams.set('schema',schema);
    const testEnv={...process.env,DATABASE_URL:scoped.toString(),DATABASE_URL_UNPOOLED:scoped.toString()};
    execFileSync(process.execPath,[require.resolve('prisma/build/index.js'),'migrate','deploy'],{env:testEnv,stdio:'pipe',timeout:30000});
    db=new PrismaService({datasourceUrl:scoped.toString()});
    services=createServices(db,{now:()=>now});
    await db.user.createMany({data:[alice,bob,carol]});
  },60000);
  afterAll(async()=>{
    await db?.$disconnect();
    if(admin){
      if(!/^test_[a-f0-9]{32}$/.test(schema))throw new Error('Unsafe test schema');
      await admin.$executeRawUnsafe(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
      await admin.$disconnect();
    }
  });
  it('plans alone, approves work, isolates three balances, and serializes token spending',async()=>{
    const planner=services.planner;
    const standalone=await planner.createTask(alice.id,{title:'A solo task',notes:'Private',kind:'TODO',timezone:'UTC',weekdays:[1,2,3,4,5,6,7],dueOn:null,target:1});
    expect((await planner.tasks(alice.id))[0].title).toBe('A solo task');
    await planner.completeTask(alice.id,standalone.id,{completed:true});
    expect((await planner.tasks(alice.id))[0].completed).toBe(true);
    expect(await planner.spaces(alice.id)).toEqual([]);
    await expect(planner.completeTask(bob.id,standalone.id,{completed:true})).rejects.toThrow('not found');

    const pairRecord=await services.pairs.createPair(alice,'Partners','UTC');
    const pair={scopeKind:'PAIR' as const,scopeId:pairRecord.id};
    await expect(planner.market(alice.id,pair)).rejects.toThrow('at least one other');
    const pairCode=await services.circles.code(alice.id,'partner',pair.scopeId);
    await services.circles.join(bob.id,pairCode.code);
    const first=await services.circles.create(alice.id,'Group 1');
    const firstCode=await services.circles.code(alice.id,'group',first.id);
    await services.circles.join(bob.id,firstCode.code);
    const second=await services.circles.create(alice.id,'Group 2');
    const secondCode=await services.circles.code(alice.id,'group',second.id);
    await services.circles.join(carol.id,secondCode.code);
    const group1={scopeKind:'GROUP' as const,scopeId:first.id},group2={scopeKind:'GROUP' as const,scopeId:second.id};
    const task=await planner.createTask(alice.id,{title:'Finish the chapter',notes:'Never shared',kind:'TODO',timezone:'UTC',weekdays:[1,2,3,4,5,6,7],dueOn:null,target:1});
    const proposals=await Promise.all([planner.propose(alice.id,task.id,pair,3),planner.propose(alice.id,task.id,group1,5),planner.propose(alice.id,task.id,group2,7)]);
    await expect(planner.decideProposal(alice.id,proposals[0].id,true)).rejects.toThrow('Another member');
    await planner.decideProposal(bob.id,proposals[0].id,true);
    await planner.decideProposal(bob.id,proposals[1].id,true);
    await planner.decideProposal(carol.id,proposals[2].id,true);
    await Promise.all([planner.completeTask(alice.id,task.id,{completed:true}),planner.completeTask(alice.id,task.id,{completed:true})]);
    expect(await db.taskAward.count({where:{proposalId:{in:proposals.map(p=>p.id)}}})).toBe(3);
    const balances=await planner.spaces(alice.id);
    expect(balances.find(s=>s.scopeId===pair.scopeId)?.balance).toBe(3);
    expect(balances.find(s=>s.scopeId===first.id)?.balance).toBe(5);
    expect(balances.find(s=>s.scopeId===second.id)?.balance).toBe(7);
    await expect(db.circleTokenEntry.updateMany({where:{circleId:first.id},data:{amount:99}})).rejects.toThrow('append-only');
    await expect(db.circleTokenEntry.create({data:{circleId:first.id,userId:alice.id,amount:-1,reason:'TASK_AWARD',sourceId:randomUUID(),idempotencyKey:randomUUID()}})).rejects.toThrow('CircleTokenEntry_amount_check');
    await expect(db.ledgerEntry.create({data:{pairId:pair.scopeId,userId:alice.id,amount:-1,reason:'TASK_AWARD',sourceId:randomUUID(),idempotencyKey:randomUUID()}})).rejects.toThrow('LedgerEntry_amount_check');
    await expect(planner.completeTask(alice.id,task.id,{completed:false})).rejects.toThrow('final');
    const market=await planner.market(bob.id,group1);
    expect(market.proposals[0].task).not.toHaveProperty('notes');
    await expect(planner.market(bob.id,group2)).rejects.toThrow('not a member');
    const reward=await planner.offer(bob.id,{...group1,title:'Coffee',expectation:'Treat you to a coffee',cost:4});
    await planner.decideReward(alice.id,reward.id,true);
    const attempts=await Promise.allSettled([planner.redeem(alice.id,reward.id,'first-request'),planner.redeem(alice.id,reward.id,'other-request')]);
    expect(attempts.filter(a=>a.status==='fulfilled')).toHaveLength(1);
    expect(await db.circleTokenEntry.count({where:{circleId:first.id,userId:alice.id,reason:'REWARD_REDEMPTION'}})).toBe(1);
    const redemption=await db.spaceRedemption.findFirstOrThrow({where:{rewardId:reward.id}});
    await Promise.all([planner.redeem(alice.id,reward.id,redemption.idempotencyKey),planner.redeem(alice.id,reward.id,redemption.idempotencyKey)]);
    expect((await planner.market(alice.id,group1)).balance).toBe(1);
    expect((await planner.market(alice.id,group2)).balance).toBe(7);
    await expect(planner.fulfill(alice.id,redemption.id)).rejects.toThrow('Only the person');
    await planner.fulfill(bob.id,redemption.id);
    expect((await db.spaceRedemption.findUniqueOrThrow({where:{id:redemption.id}})).status).toBe('FULFILLED');
  });
  it('shares group notes with new members, rejects outsiders and preserves a concurrent winner', async () => {
    const circle = await services.circles.create(alice.id, 'Shared notebook test');
    const space = { scopeKind: 'GROUP' as const, scopeId: circle.id };
    const note = await services.notes.create(alice.id, space);
    const invite = await services.circles.code(alice.id, 'group', circle.id);
    await services.circles.join(bob.id, invite.code);
    expect((await services.notes.list(bob.id, space)).map(item => item.id)).toContain(note.id);
    await expect(services.notes.get(carol.id, note.id)).rejects.toThrow('not a member');
    await expect(services.notes.create(carol.id, space)).rejects.toThrow('not a member');
    const content = { type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: 'Our shared plan' }] }] };
    const results = await Promise.allSettled([
      services.notes.edit(alice.id, note.id, { title: 'Alice’s edit', content, version: 1 }),
      services.notes.edit(bob.id, note.id, { title: 'Bob’s edit', content, version: 1 }),
    ]);
    expect(results.filter(result => result.status === 'fulfilled')).toHaveLength(1);
    const rejected = results.find(result => result.status === 'rejected') as PromiseRejectedResult;
    expect(rejected.reason.status).toBe(409);
    const stored = await services.notes.get(bob.id, note.id);
    expect(stored.version).toBe(2);
    expect(stored.content).toEqual(content);
    await services.notes.edit(bob.id, note.id, { title: 'Reviewed together', content, version: stored.version });
    expect((await services.notes.get(alice.id, note.id)).title).toBe('Reviewed together');
    const other = await services.circles.create(carol.id, 'A different notebook');
    expect(await services.notes.list(carol.id, { scopeKind: 'GROUP', scopeId: other.id })).toEqual([]);
  });
  it('keeps Personal private, shares selected sections, and lets only the owner update shared progress', async () => {
    const circle=await services.circles.create(alice.id,'Shared tasks');
    const space={scopeKind:'GROUP' as const,scopeId:circle.id};
    const invite=await services.circles.code(alice.id,'group',circle.id);
    await services.circles.join(bob.id,invite.code);
    const fields={title:'Plan our weekend',notes:'Private reminder',kind:'TODO' as const,timezone:'UTC',weekdays:[1,2,3,4,5,6,7],dueOn:null,target:1};
    const shared=await services.planner.createTask(alice.id,{...fields,spaces:[space]});
    const personal=await services.planner.createTask(alice.id,{...fields,title:'Only me'});
    expect((await services.planner.tasks(alice.id)).map(task=>task.id)).toEqual(expect.arrayContaining([shared.id,personal.id]));
    const visible=await services.planner.tasks(bob.id,space);
    expect(visible.map(task=>task.id)).toEqual([shared.id]);
    expect(visible[0]).toMatchObject({notes:'',ownerEmail:alice.email,completed:false});
    expect(JSON.stringify(visible)).not.toContain('Private reminder');
    expect((await services.planner.tasks(bob.id)).map(task=>task.id)).not.toContain(shared.id);
    await expect(services.planner.tasks(carol.id,space)).rejects.toThrow('not a member');
    await expect(services.planner.createTask(carol.id,{...fields,spaces:[space]})).rejects.toThrow('not a member');
    await expect(services.planner.completeTask(bob.id,shared.id,{completed:true})).rejects.toThrow('not found');
    await expect(services.planner.editTask(bob.id,shared.id,{...fields,spaces:[]})).rejects.toThrow('not found');
    await expect(services.planner.archiveTask(bob.id,shared.id,true)).rejects.toThrow('not found');
    await services.planner.completeTask(alice.id,shared.id,{completed:true});
    expect((await services.planner.tasks(bob.id,space))[0].completed).toBe(true);
    await services.planner.editTask(alice.id,personal.id,{...fields,title:'Now shared',spaces:[space]});
    expect((await services.planner.tasks(bob.id,space)).map(task=>task.id)).toContain(personal.id);
    await services.planner.editTask(alice.id,shared.id,{...fields,spaces:[]});
    expect((await services.planner.tasks(bob.id,space)).map(task=>task.id)).not.toContain(shared.id);
    expect((await services.planner.tasks(alice.id)).find(task=>task.id===shared.id)?.notes).toBe('Private reminder');
  });
  it('links two waiting partner spaces without losing notes, pending habits, rewards, or personal tasks', async () => {
    const people = await Promise.all(['waiting-one', 'waiting-two'].map(name => db.user.create({ data: { email: `${name}-${randomUUID()}@example.test` } })));
    const [first, second] = await Promise.all(people.map(person => services.pairs.createPair(person, 'Our waiting space', 'UTC')));
    const [firstCode, secondCode] = await Promise.all([services.circles.code(people[0].id,'partner',first.id), services.circles.code(people[1].id,'partner',second.id)]);
    const note = await services.notes.create(people[1].id, {scopeKind:'PAIR',scopeId:second.id});
    const habit = await services.goals.create(people[1].id, {title:'Read together',weekdays:[1,3],requiredCount:1,weeklyTokens:2});
    const reward = await services.rewards.create(people[1].id, {title:'Coffee',fulfillmentExpectation:'A coffee together',cost:2});
    const personal = await services.planner.createTask(people[1].id, {title:'Keep my private task',notes:'Keep this private',kind:'TODO',timezone:'UTC',weekdays:[1],dueOn:null,target:1,spaces:[{scopeKind:'PAIR',scopeId:second.id}]});
    await services.circles.join(people[1].id, firstCode.code);
    expect((await services.pairs.current(people[1].id)).members.map(member=>member.user.id).sort()).toEqual(people.map(person=>person.id).sort());
    expect((await services.notes.get(people[0].id,note.id)).scopeId).toBe(first.id);
    expect((await db.goal.findUniqueOrThrow({where:{id:habit.id}})).pairId).toBe(first.id);
    expect((await db.reward.findUniqueOrThrow({where:{id:reward.id}})).pairId).toBe(first.id);
    expect((await services.planner.tasks(people[1].id)).find(task=>task.id===personal.id)?.notes).toBe('Keep this private');
    expect((await services.planner.tasks(people[0].id,{scopeKind:'PAIR',scopeId:first.id})).find(task=>task.id===personal.id)?.notes).toBe('');
    await expect(services.circles.join(people[1].id,firstCode.code)).resolves.toEqual({kind:'partner',targetId:first.id});
    await expect(services.circles.join(people[0].id,secondCode.code)).resolves.toEqual({kind:'partner',targetId:first.id});
    await expect(services.circles.join(carol.id,firstCode.code)).rejects.toThrow('invalid or expired');
  });
  it('applies the same waiting-space fix to legacy email invitations', async () => {
    const people = await Promise.all(['email-one','email-two'].map(name=>db.user.create({data:{email:`${name}-${randomUUID()}@example.test`}})));
    await Promise.all(people.map(person=>services.pairs.createPair(person,'Waiting','UTC')));
    const invite=await services.pairs.createInvite(people[0],people[1].email);
    await services.pairs.acceptInvite(people[1],invite.token);
    expect((await services.pairs.current(people[0].id)).members).toHaveLength(2);
  });
  it('preserves an established couple and a waiting wallet when joining is refused', async () => {
    const host=await db.user.create({data:{email:`host-${randomUUID()}@example.test`}});
    const waiting=await services.pairs.createPair(host,'Waiting','UTC');
    const code=await services.circles.code(host.id,'partner',waiting.id);
    const before=await services.pairs.current(alice.id);
    await expect(services.circles.join(alice.id,code.code)).rejects.toThrow('already connected');
    expect((await services.pairs.current(alice.id)).pairId).toBe(before.pairId);
    const walletOwner=await db.user.create({data:{email:`wallet-${randomUUID()}@example.test`}});
    const walletSpace=await services.pairs.createPair(walletOwner,'Preserve wallet','UTC');
    await db.ledgerEntry.create({data:{pairId:walletSpace.id,userId:walletOwner.id,amount:3,reason:'TASK_AWARD',sourceId:randomUUID(),idempotencyKey:randomUUID()}});
    await expect(services.circles.join(walletOwner.id,code.code)).rejects.toThrow('token history');
    expect((await services.wallet.balance(walletOwner.id)).balance).toBe(3);
    expect((await services.pairs.current(walletOwner.id)).pairId).toBe(walletSpace.id);
    expect((await services.pairs.current(host.id)).members).toHaveLength(1);
  });
  it('serializes crossed partner codes into one couple', async () => {
    const people=await Promise.all(['cross-one','cross-two'].map(name=>db.user.create({data:{email:`${name}-${randomUUID()}@example.test`}})));
    const pairs=await Promise.all(people.map(person=>services.pairs.createPair(person,'Waiting','UTC')));
    const codes=await Promise.all(pairs.map((pair,index)=>services.circles.code(people[index].id,'partner',pair.id)));
    const results=await Promise.allSettled([services.circles.join(people[0].id,codes[1].code),services.circles.join(people[1].id,codes[0].code)]);
    expect(results.some(result=>result.status==='fulfilled')).toBe(true);
    const current=await Promise.all(people.map(person=>services.pairs.current(person.id)));
    expect(current[0].pairId).toBe(current[1].pairId);
    expect(current[0].members).toHaveLength(2);
  });
});
